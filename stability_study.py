'''
Collects all warnings and errors from saved runs results
Saves summary tables

Initial version of code generated by Claude
'''

import pandas as pd
from pathlib import Path

import sys

# Label comes from the Makefile (make <target> LABEL=...); defaults to baseline
if len(sys.argv) > 1:
    label = sys.argv[1]
else:
    label = "baseline"

# Number of workers for parallization comes from Makefile
if len(sys.argv) > 2:
    N_WORKERS = int(sys.argv[2])
    label = label + "_" + str(N_WORKERS) + "workers"
else:
    N_WORKERS = 1

runs_file = Path("results/raw") / label / "runs.csv"
out_dir = Path("results/warnings") / label
out_dir.mkdir(parents=True, exist_ok=True)

runs = pd.read_csv(runs_file)

# Empty strings are read back from the CSV as NaN, so set them back to ""
for column in ["failure_reason", "error_message", "warnings"]:
    runs[column] = runs[column].fillna("")

group_columns = ["experiment", "pi_treat", "model", "n_sample"]

# Errors: one row per rep that raised an exception
errors = runs[runs["error_message"] != ""]
error_counts = (errors.groupby(group_columns + ["failure_reason", "error_message"])
                      .size()
                      .reset_index(name="count"))

# Warnings: split the " | "-joined text so each warning gets its own row
with_warnings = runs[runs["warnings"] != ""].copy()
with_warnings["warning"] = with_warnings["warnings"].str.split(" | ", regex=False)
each_warning = with_warnings.explode("warning")

warning_counts = (each_warning.groupby(group_columns + ["warning"])
                              .size()
                              .reset_index(name="count"))

# Reps affected (a rep with 3 warnings counts once here)
reps_with_warnings = (with_warnings.groupby(group_columns)
                                   .size()
                                   .reset_index(name="n_reps_with_warnings"))

error_counts.to_csv(out_dir / "error_counts.csv", index=False)
warning_counts.to_csv(out_dir / "warning_counts.csv", index=False)
reps_with_warnings.to_csv(out_dir / "reps_with_warnings.csv", index=False)