'''
Counts failures (errors, warnings, non-convergence) from saved runs results
Saves a summary table

Initial version of code generated by Claude
'''

import pandas as pd
from pathlib import Path

import sys

# Full label comes from the Makefile
if len(sys.argv) > 1:
    label = sys.argv[1]
else:
    label = "baseline"

runs_file = Path("results/raw") / label / "runs.csv"
out_dir = Path("results/warnings") / label
out_dir.mkdir(parents=True, exist_ok=True)

runs = pd.read_csv(runs_file)

# Empty strings are read back from the CSV as NaN, so set them back to ""
runs["failure_reason"] = runs["failure_reason"].fillna("")

group_columns = ["experiment", "pi_treat", "model", "n_sample"]

# Number of repetitions with each failure reason, per condition
failures = runs[runs["failure_reason"] != ""]
failure_counts = (failures.groupby(group_columns + ["failure_reason"])
                          .size()
                          .reset_index(name="count"))

failure_counts.to_csv(out_dir / "failure_counts.csv", index=False)