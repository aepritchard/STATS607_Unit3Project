'''
Analyzes run time vs n for all experiments
'''

import logging
import tempfile
from pathlib import Path
from time import perf_counter
import pandas as pd
import matplotlib.pyplot as plt

from simulation import SimulationStudy
from scenarios import make_scenarios_for_all_n_samples
import matplotlib.pyplot as plt

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s")

import sys

# Label comes from the Makefile (make <target> LABEL=...); defaults to baseline
if len(sys.argv) > 1:
    label = sys.argv[1]
else:
    label = "baseline"

# Number of workers for parallization comes from Makefile
if len(sys.argv) > 2:
    N_WORKERS = int(sys.argv[2])
    label = label + "_" + str(N_WORKERS) + "workers"
else:
    N_WORKERS = 1
    
COMPLEXITY_DIR = Path("results/complexity")

### Make scenarios for complexity analysis
# Initial unit 2 study did not take long to run, add larger sample sizes
#   to test how run time changes
n_samples = [100, 500, 1000, 5000, 10000, 25000, 50000]
SCENARIOS = {}
make_scenarios_for_all_n_samples(n_samples, SCENARIOS)

# 
def time_all_scenarios():
    COMPLEXITY_DIR.mkdir(parents=True, exist_ok=True)

    rows = []
    for scenario_id, settings in SCENARIOS.items():
        # Use scratch directory to have blank start and throw away results
        with tempfile.TemporaryDirectory() as scratch_dir:
            study = SimulationStudy({scenario_id: settings}, label=label, n_workers=N_WORKERS, out_dir=scratch_dir)

            start = perf_counter()
            study.run()
            seconds = perf_counter() - start

        logging.info("Timed %s: %.1f seconds", scenario_id, seconds)
        rows.append({
            "scenario_id": scenario_id,
            "experiment": settings["experiment"],
            "pi_treat": settings["pi_treat"],
            "n_sample": settings["n_sample"],
            "seconds": seconds,
        })

    # Save runtimes
    runtimes = pd.DataFrame(rows)
    runtimes_path = COMPLEXITY_DIR / f"{label}_runtimes.csv"
    runtimes.to_csv(runtimes_path, index=False)
    logging.info("Runtimes written to %s", runtimes_path)

    return runtimes

def plot_runtime_vs_n(runtimes, plot_baseline=True):
    '''
    Plots runtime of one full scenario vs n, one panel per experiment
    Log-log axes, dots connected
    Experiment 2 has one line per % treated

    Initial version of function generated by Claude
    '''
    versions = [(runtimes, label, "-", "full")]
    if plot_baseline:
        baseline_complexity = pd.read_csv(COMPLEXITY_DIR / "baseline_runtimes.csv")
        versions.append((baseline_complexity, "baseline", "--", "none"))

    pi_treat_colors = {0.75: "C0", 0.50: "C1", 0.25: "C2"}

    experiments = ["e1_table1", "e2_pct_treated", "e3_cutoffs", "e4_covariate", "e5_joint_dist"]

    fig, axes = plt.subplots(2, 3, figsize=(10, 8))
    axes = axes.flatten()

    fig, axes = plt.subplots(2, 3, figsize=(10, 8))
    axes = axes.flatten()

    for ax, experiment in zip(axes, experiments):
        for version_runtimes, version_name, linestyle, marker_fill in versions:
            subset = version_runtimes[version_runtimes["experiment"] == experiment]

            for pi_treat in sorted(subset["pi_treat"].unique(), reverse=True):
                rows = subset[subset["pi_treat"] == pi_treat].sort_values("n_sample")
                n_sample = rows["n_sample"].to_numpy()
                seconds = rows["seconds"].to_numpy()

                if experiment == "e2_pct_treated":
                    label = f"{int(pi_treat * 100)}% treated, {version_name}"
                else:
                    label = version_name

                if marker_fill == "none":
                    markerfacecolor = "none"
                else:
                    markerfacecolor = pi_treat_colors[pi_treat]

                ax.plot(n_sample, seconds, color=pi_treat_colors[pi_treat],
                        linestyle=linestyle, marker="o", markerfacecolor=markerfacecolor,
                        linewidth=1.5, markersize=5, label=label)

        all_n_samples = sorted(runtimes["n_sample"].unique())
        ax.set_xscale("log")
        ax.set_yscale("log")
        ax.set_xticks(all_n_samples)
        ax.set_xticklabels([str(n) for n in all_n_samples], rotation=45)
        ax.minorticks_off()
        ax.set_title(experiment, fontsize=11)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        ax.legend(frameon=False, fontsize=8)

    # Only 5 experiments, so hide the unused sixth panel
    axes[5].set_visible(False)

    fig.supxlabel(r"Sample size $n$")
    fig.supylabel("Runtime of one scenario (seconds)")
    fig.tight_layout()

    fig.savefig(Path(COMPLEXITY_DIR) / f"{label}_runtime_vs_n.png", dpi=300, bbox_inches="tight")
    plt.close(fig)

if __name__ == "__main__":
    runtimes = time_all_scenarios()
    plot_runtime_vs_n(runtimes)