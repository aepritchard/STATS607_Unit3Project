'''
Analyzes run time vs n for all experiments
'''

import logging
import tempfile
from pathlib import Path
from time import perf_counter
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from simulation import SimulationStudy
from scenarios import make_scenarios_for_all_n_samples

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s")

import sys

# Full label and number of workers come from the Makefile
if len(sys.argv) > 1:
    label = sys.argv[1]
else:
    label = "baseline"

if len(sys.argv) > 2:
    N_WORKERS = int(sys.argv[2])
else:
    N_WORKERS = 1

COMPLEXITY_DIR = Path("results/complexity")

### Make scenarios for complexity analysis
# Initial unit 2 study did not take long to run, add larger sample sizes
#   to test how run time changes
n_samples = [100, 500, 1000, 5000, 10000, 25000, 50000]
SCENARIOS = {}
make_scenarios_for_all_n_samples(n_samples, SCENARIOS)

# One panel per experiment and proportion treated
CONDITIONS = [
    {"label": "E1: baseline (Table 1)", "experiment": "e1_table1", "pi_treat": 0.75},
    {"label": "E2: 75% treated", "experiment": "e2_pct_treated", "pi_treat": 0.75},
    {"label": "E2: 50% treated", "experiment": "e2_pct_treated", "pi_treat": 0.50},
    {"label": "E2: 25% treated", "experiment": "e2_pct_treated", "pi_treat": 0.25},
    {"label": "E3: cut offs 0.95, 1.5", "experiment": "e3_cutoffs", "pi_treat": 0.75},
    {"label": "E4: Z = U + V", "experiment": "e4_covariate", "pi_treat": 0.75},
    {"label": "E5: (U, V) ~ Beta(2, 5)", "experiment": "e5_joint_dist", "pi_treat": 0.75},
]

#
def time_all_scenarios():
    COMPLEXITY_DIR.mkdir(parents=True, exist_ok=True)

    rows = []
    for scenario_id, settings in SCENARIOS.items():
        # Use scratch directory to have blank start and throw away results
        with tempfile.TemporaryDirectory() as scratch_dir:
            study = SimulationStudy({scenario_id: settings}, label=label, n_workers=N_WORKERS, out_dir=scratch_dir)

            start = perf_counter()
            study.run()
            seconds = perf_counter() - start

        logging.info("Timed %s: %.1f seconds", scenario_id, seconds)
        rows.append({
            "scenario_id": scenario_id,
            "experiment": settings["experiment"],
            "pi_treat": settings["pi_treat"],
            "n_sample": settings["n_sample"],
            "seconds": seconds,
        })

    # Save runtimes
    runtimes = pd.DataFrame(rows)
    runtimes_path = COMPLEXITY_DIR / f"{label}_runtimes.csv"
    runtimes.to_csv(runtimes_path, index=False)
    logging.info("Runtimes written to %s", runtimes_path)

    return runtimes

def plot_runtime_vs_n():
    '''
    Plots runtime of one full scenario vs n for every saved version in COMPLEXITY_DIR
    Each *_runtimes.csv file is one version, named by the file name (e.g. optimized_4workers)
    One panel per experiment / proportion treated, one color per version
    Log-log axes, dots connected

    Initial version of function generated by Claude
    '''
    # Find every saved version
    versions = []
    for runtimes_path in sorted(COMPLEXITY_DIR.glob("*_runtimes.csv")):
        version_name = runtimes_path.stem.removesuffix("_runtimes")
        version_runtimes = pd.read_csv(runtimes_path)
        versions.append((version_name, version_runtimes))

    # Sample sizes across all versions, for the x axis ticks
    all_n_samples = set()
    for version_name, version_runtimes in versions:
        all_n_samples.update(version_runtimes["n_sample"].unique())
    all_n_samples = sorted(all_n_samples)

    fig, axes = plt.subplots(2, 4, figsize=(14, 8))
    axes = axes.flatten()

    for ax, condition in zip(axes, CONDITIONS):
        for version_number, (version_name, version_runtimes) in enumerate(versions):
            is_experiment = version_runtimes["experiment"] == condition["experiment"]
            is_pi_treat = np.isclose(version_runtimes["pi_treat"], condition["pi_treat"])
            rows = version_runtimes[is_experiment & is_pi_treat].sort_values("n_sample")

            n_sample = rows["n_sample"].to_numpy()
            seconds = rows["seconds"].to_numpy()

            # C0, C1, C2, ... are matplotlib's default colors, one per version
            ax.plot(n_sample, seconds, color=f"C{version_number}", marker="o",
                    linewidth=1.5, markersize=5, label=version_name)

        ax.set_xscale("log")
        ax.set_yscale("log")
        ax.set_xticks(all_n_samples)
        ax.set_xticklabels([str(n) for n in all_n_samples], rotation=45)
        ax.minorticks_off()
        ax.set_title(condition["label"], fontsize=11)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)

    # Only 7 conditions, so hide the unused eighth panel
    axes[7].set_visible(False)

    # One legend for the whole figure: versions are the same in every panel
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", ncol=len(versions), frameon=False)

    fig.supxlabel(r"Sample size $n$")
    fig.supylabel("Runtime of one scenario (seconds)")
    fig.tight_layout(rect=[0, 0, 1, 0.94])

    fig.savefig(COMPLEXITY_DIR / "runtime_vs_n_all_versions.png", dpi=300, bbox_inches="tight")
    plt.close(fig)

if __name__ == "__main__":
    time_all_scenarios()
    plot_runtime_vs_n()